// Optional browser acceptance, never imported by the app or unit test discovery.
// Start workbenchPreview.mjs with this script's fixture path and --composer-fixture.
// PLAYWRIGHT_MODULE may point to a bundled playwright/index.mjs; no install needed.
import assert from "node:assert/strict";
import {writeFile, mkdir} from "node:fs/promises";
import {fileURLToPath} from "node:url";
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const fixturePath = process.argv[2] || "/private/tmp/fm-task1-ux-fixture.json";
const evidence = fileURLToPath(new URL("../../../docs/acceptance/task1-ux/", import.meta.url));
await mkdir(evidence, {recursive: true});
const fixtureSession = `task1-${Date.now()}`;
let completed = false;
const checks = [], errors = [], warnings = [], consoleErrors = [], failedRequests = [], external = [], submissions = [];
const browser = await chromium.launch({headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE ? {executablePath: process.env.PLAYWRIGHT_EXECUTABLE} : {})});
const context = await browser.newContext({viewport: {width: 1440, height: 1000}, permissions: ["clipboard-read", "clipboard-write"]});
const page = await context.newPage();
page.setDefaultTimeout(7000);
await context.route("**/*", route => {
  const url = new URL(route.request().url());
  if (url.hostname !== "127.0.0.1") {external.push(url.origin);return route.abort();}
  if (route.request().method() === "POST" && url.pathname === "/api/v1/tasks") submissions.push(route.request().postDataJSON());
  return route.continue();
});
page.on("requestfailed", request => failedRequests.push({url: request.url(), failure: request.failure()}));
page.on("pageerror", error => errors.push(error.message));
page.on("console", message => {if (message.type() === "error") consoleErrors.push(message.text());if (message.type() === "warning") warnings.push(message.text());});
const configure = settings => writeFile(fixturePath, JSON.stringify({...settings, fixtureSession}));
const visible = async (locator, name) => {await locator.waitFor({state: "visible"}); checks.push(name);};
const check = (condition, name) => {assert.ok(condition, name); checks.push(name);};
const shot = name => page.screenshot({path: `${evidence}${name}.png`, fullPage: true});
const go = async settings => {await configure(settings);await page.goto("http://127.0.0.1:5183");};
const noOverflow = async name => check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), name);
const select = async title => {
  await page.locator(".run-picker > summary").click();
  await page.locator("[data-run-choice]").filter({hasText: title}).click();
};
try {
  await go({auth: "unavailable"});
  await visible(page.getByText("Server unavailable", {exact: true}), "login server unavailable");
  check(!(await page.textContent("body")).includes("Private fixture diagnostic"), "login hides internal server diagnostics");
  await shot("login-retry-desktop");
  await configure({auth: "anonymous"});
  await page.getByRole("button", {name: "Retry connection"}).click();
  await visible(page.getByRole("heading", {name: "Sign in to continue"}), "login retry recovers without redirect");
  check((await page.getByRole("link", {name: "Continue with Google"}).getAttribute("href")).endsWith("/api/v1/auth/google/login"), "Google sign-in retains API path");
  await go({auth: "expired"});
  await visible(page.getByText("Session expired", {exact: true}), "expired session has sign-in action");
  await go({auth: "failed"});
  await visible(page.getByText("Access unavailable", {exact: true}), "authentication failure differs from outage");
  await page.route("**/api/v1/auth/me", route => route.abort("internetdisconnected"));
  await go({});
  await visible(page.getByText("Connection interrupted", {exact: true}), "temporary network error has retry");
  await page.unroute("**/api/v1/auth/me");
  await configure({authDelayMs: 600, workspaceDelayMs: 900, runs: "empty"});
  await page.getByRole("button", {name: "Retry connection"}).click();
  await visible(page.getByRole("heading", {name: "Checking session…"}), "authentication loading is visible");
  await visible(page.getByRole("heading", {name: "Loading your workspaces…"}), "workspace loading is visible");
  await visible(page.getByRole("button", {name: "Create Simulation", exact: true}), "workspace bootstrap opens simulation");
  await go({workspace: "error"});
  await visible(page.getByRole("button", {name: "Try again", exact: true}), "workspace failure provides retry");
  await shot("workspace-retry-desktop");
  await configure({runs: "empty"});
  await page.getByRole("button", {name: "Try again", exact: true}).click();
  await visible(page.locator(".workbench-runs > p"), "empty workspace has honest guidance");
  await shot("empty-desktop");
  await noOverflow("empty desktop has no horizontal overflow");
  await page.getByRole("button", {name: "Create Simulation", exact: true}).click();
  await visible(page.getByRole("dialog", {name: "Create simulation"}), "create simulation modal opens");
  await shot("composer-desktop");
  check(await page.locator("#task-directive").evaluate(node => document.activeElement === node), "task input receives initial keyboard focus");
  check(await page.getByRole("button", {name: "Run simulation", exact: true}).isDisabled(), "blank task disables submission");
  await page.locator("#task-directive").fill("Fixture only: summarize these local acceptance checks in three bullets.");
  for (const mode of ["single", "fixed", "adaptive"]) {
    await page.locator(`input[name=executionMode][value=${mode}]`).check();
    check(await page.locator(`input[value=${mode}]`).isChecked(), `${mode} mode selection works`);
  }
  await page.locator(".composer-utility > summary").click();
  await page.locator("input[value=single_agent]").check();
  await visible(page.locator("#task-agent"), "individual specialist selection remains available");
  await page.locator("input[value=single]").check();
  await page.locator(".composer-context > summary").click();
  await visible(page.locator("#context-files"), "optional file upload remains available");
  check(await page.locator("#benchmark-dataset").isDisabled(), "empty benchmark registry is explained and disabled");
  await page.locator("#context-files").setInputFiles({name: "fixture.txt", mimeType: "text/plain", buffer: Buffer.from("Explicit fixture reference context. No provider executes.")});
  await visible(page.locator(".upload-preview summary"), "reference file upload has a prepared preview");
  await shot("composer-context-desktop");
  await page.getByRole("button", {name: "Run simulation", exact: true}).focus();
  await page.keyboard.press("Tab");
  check(await page.getByRole("button", {name: "Close Create simulation"}).evaluate(node => document.activeElement === node), "modal Tab wraps to first control");
  await page.keyboard.press("Shift+Tab");
  check(await page.getByRole("button", {name: "Run simulation", exact: true}).evaluate(node => document.activeElement === node), "modal Shift Tab wraps to last control");
  await configure({runs: "empty", createDelayMs: 900});
  await page.getByRole("button", {name: "Run simulation", exact: true}).click();
  await visible(page.getByText("Submitting run… Keep this dialog open until the request finishes."), "submission has loading feedback");
  check(await page.locator("#task-directive").isDisabled(), "submission disables editing");
  await page.keyboard.press("Escape");
  check(await page.getByRole("dialog").isVisible(), "pending submission cannot dismiss modal");
  await page.getByRole("dialog").waitFor({state: "hidden"});
  await visible(page.getByText("Waiting to start. Updates appear automatically.", {exact: false}), "creation opens acknowledged queued run");
  check(submissions.length === 1 && submissions[0].executionMode === "single" && submissions[0].uploadIds.length === 1, "one mocked submission preserves mode and upload API payload");
  await page.waitForFunction(() => document.activeElement?.hasAttribute("data-run-heading"));
  check(await page.locator("[data-run-heading]").evaluate(node => document.activeElement === node), "creation returns focus to new run title");
  await go({phase: 2});
  await select("Fixture · Live recorded transitions");
  await visible(page.getByText("Working: Analysis Agent.", {exact: false}), "running state uses persisted active agent");
  await shot("running-desktop");
  await configure({phase: 4});
  await visible(page.getByText("Final answer available below.", {exact: false}), "polling updates running snapshot to completed");
  await visible(page.getByRole("region", {name: "Final answer content"}), "completed answer is primary and readable");
  check(!(await page.locator(".execution-flow-details").getAttribute("open")), "technical graph starts collapsed");
  await page.getByRole("button", {name: "Raw", exact: true}).click();
  check(await page.getByRole("button", {name: "Raw", exact: true}).getAttribute("aria-pressed") === "true", "Raw output view works");
  const raw = await page.locator(".output-body pre").textContent();
  await page.getByRole("button", {name: "Copy output", exact: true}).click();
  await visible(page.getByText("Copied", {exact: true}), "copy reports successful clipboard write");
  check(await page.evaluate(() => navigator.clipboard.readText()) === raw, "copied raw output equals persisted fixture output");
  await page.getByRole("button", {name: "Rendered", exact: true}).click();
  await shot("completed-desktop");
  await noOverflow("completed desktop has no horizontal overflow");
  await page.getByRole("button", {name: "Focus reading"}).click();
  await visible(page.getByRole("dialog", {name: "Final answer"}), "focus reader opens");
  await page.keyboard.press("Escape");
  check(await page.getByRole("button", {name: "Focus reading"}).evaluate(node => document.activeElement === node), "focus reader restores keyboard focus");
  await page.locator(".execution-flow-details > summary").click();
  await visible(page.getByRole("heading", {name: "Execution flow", exact: true}), "recorded graph remains accessible");
  await page.getByRole("button", {name: "Inspect route decision", exact: true}).click();
  await visible(page.getByRole("button", {name: "Technical details", exact: true}), "routing evidence remains accessible");
  await select("Fixture · Failed Analysis stage");
  await visible(page.getByText("Execution stopped.", {exact: false}), "failed run offers evidence recovery guidance");
  await page.evaluate(() => window.scrollTo(0, 0));
  await shot("failed-desktop");
  await page.getByRole("button", {name: "Review failed stage: Analysis Agent"}).click();
  check(await page.getByRole("button", {name: "Technical details", exact: true}).getAttribute("aria-pressed") === "true", "failed-stage review opens technical evidence");
  await select("Fixture · Single direct answer");
  check(await page.getByRole("button", {name: "Output", exact: true}).getAttribute("aria-pressed") === "true", "changing runs restores primary output view");
  await page.setViewportSize({width: 390, height: 844});
  await shot("completed-mobile");
  await noOverflow("completed phone has no horizontal overflow");
  check(await page.getByRole("button", {name: "Live Simulation", exact: true}).locator("span").evaluate(node => node.getBoundingClientRect().width > 30), "phone navigation labels remain readable");
  await page.getByRole("button", {name: "Create Simulation", exact: true}).click();
  await shot("composer-mobile");
  await noOverflow("phone modal has no horizontal overflow");
  check((await page.locator("#task-directive").boundingBox()).width > 280, "phone task input is wide enough to read");
  await page.keyboard.press("Escape");
  await configure({datasets: "registered", create: "validation", createDelayMs: 250});
  await page.getByRole("button", {name: "Create Simulation", exact: true}).click();
  await visible(page.locator("#task-directive"), "phone modal reopens");
  await page.locator("#task-directive").fill("Fixture corrective task");
  await page.locator(".composer-context > summary").click();
  await page.locator("#benchmark-dataset").selectOption("fixture-employee-small");
  check(await page.locator("#benchmark-dataset").inputValue() === "fixture-employee-small", "registered dataset selection remains available");
  await page.getByRole("button", {name: "Run simulation", exact: true}).click();
  await visible(page.getByText("Fixture validation rejected this configuration.", {exact: false}), "validation rejection keeps a useful form error");
  check(await page.locator("#task-directive").inputValue() === "Fixture corrective task", "validation rejection preserves the task draft");
  await configure({create: "unknown", createDelayMs: 250});
  await page.getByRole("button", {name: "Run simulation", exact: true}).click();
  await visible(page.getByText("The submission outcome is not confirmed.", {exact: false}), "uncertain submission directs user to History");
  check(await page.getByRole("dialog").isVisible(), "uncertain submission preserves modal");
  check(submissions.length === 3, "creation errors never automatically resubmit");
  await page.keyboard.press("Escape");
  await configure({logout: "error", logoutDelayMs: 700});
  await page.getByRole("button", {name: "Sign out", exact: true}).click();
  await visible(page.getByRole("button", {name: "Signing out…"}), "sign out announces progress");
  check(await page.getByRole("button", {name: "Signing out…"}).isDisabled(), "sign out prevents duplicate requests");
  await visible(page.getByText("Sign out could not be confirmed.", {exact: false}), "failed sign out preserves session and offers retry");
  await configure({});
  await page.getByRole("button", {name: "Sign out", exact: true}).click();
  await visible(page.getByRole("heading", {name: "Sign in to continue"}), "sign out retry succeeds");
  await go({tasks: "expired"});
  await visible(page.getByText("Session expired", {exact: true}), "workspace API 401 ends authenticated view");
  await go({tasks: "error"});
  await visible(page.getByRole("button", {name: "Retry loading simulations"}), "simulation load error offers retry");
  check(await page.getByRole("button", {name: "Create Simulation", exact: true}).isDisabled(), "unavailable simulation data disables creation with explanation");
  await configure({tasksDelayMs: 700});
  await page.getByRole("button", {name: "Retry loading simulations"}).click();
  await visible(page.getByRole("button", {name: "Retrying…"}), "simulation retry announces loading");
  check(await page.getByRole("button", {name: "Retrying…"}).isDisabled(), "simulation retry prevents duplicate clicks");
  await visible(page.getByRole("region", {name: "Final answer content"}), "simulation load retry recovers");
  const independent = await browser.newContext({viewport: {width: 1280, height: 800}});
  await independent.route("**/*", route => {
    if (new URL(route.request().url()).hostname !== "127.0.0.1") {external.push(route.request().url());return route.abort();}
    return route.continue();
  });
  await independent.addInitScript(() => Object.defineProperty(window, "localStorage", {get() {throw new DOMException("Fixture storage blocked", "SecurityError");}}));
  const independentPage = await independent.newPage();
  independentPage.on("pageerror", error => errors.push(error.message));
  await independentPage.goto("http://127.0.0.1:5183");
  await visible(independentPage.locator("#workspace-switcher-select"), "independent browser with storage blocked still opens workspace");
  await independentPage.locator("#workspace-switcher-select").selectOption("WS-fixture-org");
  await visible(independentPage.getByText("Member · Organization", {exact: true}), "independent browser can select an authorized workspace");
  await independent.close();
  check(errors.length === 0, "no uncaught browser errors");
  check(external.length === 0, "no external or provider requests");
  completed = true;
} catch (error) {
  await shot("failure-diagnostic");
  console.error(JSON.stringify({body: await page.locator("body").innerText(), consoleErrors, failedRequests}));
  throw error;
} finally {
  await writeFile(`${evidence}browser-results.json`, JSON.stringify({completed, checks, passed: checks.length, errors, warnings: [...new Set(warnings)], expectedHttpAndNetworkErrors: [...new Set(consoleErrors)], failedRequests, externalRequests: external, mockSubmissions: submissions.length, fixtureOnly: true, viewport: ["1440x1000", "390x844"]}, null, 2) + "\n");
  await browser.close();
}
console.log(JSON.stringify({passed: checks.length, errors, warnings: [...new Set(warnings)], expectedHttpAndNetworkErrors: [...new Set(consoleErrors)], failedRequests, externalRequests: external, evidence}));
